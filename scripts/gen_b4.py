#!/usr/bin/env python3
"""Generate the Lean files of the column b = 4 from tools/column/b4_shapes.txt.gz.

* Cgt/Col/B4Data.lean: one witness per shape, as run-length text (`T4E4F4`), split into string
  literals, and the key trees `colB4U`, `colB4N` computed from it (`Cgt/Col/Text.lean`).
* Cgt/Col/B4Check<i>.lean: one chunk of the finite check per file, evaluated by `native_decide`.
* Cgt/Col/B4Checks.lean: the chunks assembled into `hcU4` and `hcN4`.

Usage: python3 scripts/gen_b4.py [CHUNKS_U CHUNKS_N]   (default 2 and 6)
"""
import gzip
import sys

SHAPES = 'tools/column/b4_shapes.txt.gz'
K = 2          # the anchor
PART = 300000  # characters per string literal
nu, nn = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (2, 6)


def rle(shape):
    """The smallest witness of a shape, run by run."""
    sk, gs = shape.split('|')
    lens, cur = [], K
    for c in gs:
        cur += int(c)
        lens.append(cur)
    out = ''
    for i in range(0, len(sk), 2):
        c, v = sk[i], sk[i + 1]
        n = 2 if v == 'D' else lens[ord(v) - 97] if v >= 'a' else int(v)
        out += ('E' if c == '.' else c) + str(n)
    return out


U, N = [], []
for line in gzip.open(SHAPES, 'rt'):
    x = line.strip()
    if x:
        (U if x[0] == 'U' else N).append(rle(x[1:]))


def parts(ws):
    out, cur = [], ''
    for w in ws:
        if len(cur) + len(w) + 1 > PART:
            out.append(cur)
            cur = ''
        cur += w + ';'
    if cur:
        out.append(cur)
    return out


HEADER = 'Machine-generated by `scripts/gen_b4.py`'
pu, pn = parts(U), parts(N)
with open('Cgt/Col/B4Data.lean', 'w') as f:
    f.write('import Cgt.Col.Text\n\n')
    f.write(f'/-! {HEADER}: the certificate of the column `b = 4`, one witness per key\n'
            f'({len(U)} Left-stop keys, {len(N)} normal-play keys), and the key trees computed from it. -/\n\n')
    f.write('namespace Cgt\nnamespace Col\n\n')
    for name, ps in (('b4U', pu), ('b4N', pn)):
        for i, p in enumerate(ps):
            f.write(f'def {name}{i} : String :=\n  "{p}"\n\n')
        f.write(f'def {name}Parts : List String := [{", ".join(f"{name}{i}" for i in range(len(ps)))}]\n\n')
    f.write(f'/-- The {len(U)} Left-stop keys. -/\ndef colB4U : LTree := treeOfKeys (keysOfText ruleF b4UParts)\n\n')
    f.write(f'/-- The {len(N)} normal-play keys. -/\ndef colB4N : LTree := treeOfKeys (keysOfText ruleF b4NParts)\n\n')
    f.write('end Col\nend Cgt\n')


def sizes(total, k):
    q, r = divmod(total, k)
    return [q + (1 if i < r else 0) for i in range(k)]


su, sn = sizes(len(U), nu), sizes(len(N), nn)
PU = '(fun k => (witOf ruleF k).all (chkU ruleF colB4U colB4N))'
PN = '(fun k => (witOf ruleF k).all (chkN ruleF colB4N))'
files = []
idx = 0
for mode, ss, tree, pred in (('U', su, 'colB4U', PU), ('N', sn, 'colB4N', PN)):
    start = 0
    for i, n in enumerate(ss):
        name = f'B4Check{idx}'
        files.append(name)
        with open(f'Cgt/Col/{name}.lean', 'w') as f:
            f.write('import Cgt.Col.B4Data\n\n')
            f.write(f'/-! {HEADER}: part {idx} of the finite check of the column `b = 4`, evaluated by\n'
                    '`native_decide`, which trusts the Lean compiler: it adds an axiom asserting the result of the\n'
                    'compiled evaluation. -/\n\n')
            f.write('namespace Cgt\nnamespace Col\n\n')
            f.write(f'theorem chkB4{mode}_{i} : (({tree}.toList.drop {start}).take {n}).all {pred} = true := by\n'
                    '  native_decide\n\n')
            f.write('end Col\nend Cgt\n')
        start += n
        idx += 1


def assemble(mode, ss, tree, pred, stmt):
    arms = '\n'.join(f'      | {i}, _ => exact chkB4{mode}_{i}' for i in range(len(ss)))
    return (f'theorem hc{mode}4 : {stmt} := by\n'
            f'  have h : {tree}.toList.all {pred} = true :=\n'
            f'    all_of_sizes _ {ss} _ (by native_decide) fun i hi => by\n'
            f'      match i, hi with\n{arms}\n'
            f'      | _ + {len(ss)}, h => exact absurd h (by simp)\n'
            '  simp only [List.all_eq_true] at h\n  exact h\n\n')


with open('Cgt/Col/B4Checks.lean', 'w') as f:
    f.write('import Cgt.Col.Sound\n' + ''.join(f'import Cgt.Col.{n}\n' for n in files) + '\n')
    f.write(f'/-! {HEADER}: the chunks of the finite check of the column `b = 4`, assembled. -/\n\n')
    f.write('namespace Cgt\nnamespace Col\n\n')
    f.write(assemble('U', su, 'colB4U', PU,
                     '∀ k ∈ colB4U.toList, ∀ W ∈ witOf ruleF k, chkU ruleF colB4U colB4N W = true'))
    f.write(assemble('N', sn, 'colB4N', PN,
                     '∀ k ∈ colB4N.toList, ∀ W ∈ witOf ruleF k, chkN ruleF colB4N W = true'))
    f.write('end Col\nend Cgt\n')

print(f'{len(U)} U + {len(N)} N witnesses; {len(pu)} + {len(pn)} string parts; {len(files)} check files')
print('U chunks', su)
print('N chunks', sn)
