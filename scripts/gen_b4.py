#!/usr/bin/env python3
"""Generate the Lean files of the column b = 4 from tools/column/b4_shapes.txt.gz.

* Cgt/Col/B4Data.lean: one witness per shape, as run-length text (`T4E4F4`), split into string
  literals, and the key trees `colB4U`, `colB4N` computed from it (`Cgt/Col/Text.lean`).
* Cgt/Col/B4Check<i>.lean: one chunk of the finite check per file, evaluated by `native_decide`.
* Cgt/Col/B4Checks.lean: the chunks assembled into `hcU4` and `hcN4`.

With `--star`: the exact values `Tᵃ□⁴Fᵃ = ∗` (`a ≥ 5`) from tools/column/b4_star_shapes.txt.gz, with
`≤ ∗` keys (mode `S`, checked by `chkS`) and the gap rule `ruleF2`; the files are B4SData.lean,
B4SCheck<i>.lean and B4SChecks.lean (`hcS4S`, `hcN4S`).

Usage: python3 scripts/gen_b4.py [--star] [CHUNKS_1 CHUNKS_N]   (default 2 and 6; with --star 1 and 8)
"""
import gzip
import sys

STAR = '--star' in sys.argv
args = [a for a in sys.argv[1:] if a != '--star']
SHAPES = 'tools/column/b4_star_shapes.txt.gz' if STAR else 'tools/column/b4_shapes.txt.gz'
P, LP, RULE, M1 = ('B4S', 'b4s', 'ruleF2', 'S') if STAR else ('B4', 'b4', 'ruleF', 'U')
SUF = '4S' if STAR else '4'
WHAT = 'the exact values of the column `b = 4`' if STAR else 'the column `b = 4`'
KIND1 = '`≤ ∗`' if STAR else 'Left-stop'
K = 2          # the anchor
PART = 300000  # characters per string literal
nu, nn = (int(args[0]), int(args[1])) if len(args) > 1 else ((1, 8) if STAR else (2, 6))


def rle(shape):
    """The smallest witness of a shape, run by run."""
    sk, gs = shape.split('|')
    lens, cur = [], K
    for c in gs:
        cur += int(c)
        lens.append(cur)
    out = ''
    for i in range(0, len(sk), 2):
        c, v = sk[i], sk[i + 1]
        n = 2 if v == 'D' else lens[ord(v) - 97] if v >= 'a' else int(v)
        out += ('E' if c == '.' else c) + str(n)
    return out


U, N = [], []
for line in gzip.open(SHAPES, 'rt'):
    x = line.strip()
    if x:
        (U if x[0] == M1 else N).append(rle(x[1:]))


def parts(ws):
    out, cur = [], ''
    for w in ws:
        if len(cur) + len(w) + 1 > PART:
            out.append(cur)
            cur = ''
        cur += w + ';'
    if cur:
        out.append(cur)
    return out


HEADER = 'Machine-generated by `scripts/gen_b4.py`'
pu, pn = parts(U), parts(N)
with open(f'Cgt/Col/{P}Data.lean', 'w') as f:
    f.write('import Cgt.Col.Text\n' + ('import Cgt.Col.RuleF2\n' if STAR else '') + '\n')
    f.write(f'/-! {HEADER}: the certificate of {WHAT}, one witness per key\n'
            f'({len(U)} {KIND1} keys, {len(N)} normal-play keys), and the key trees computed from it. -/\n\n')
    f.write('namespace Cgt\nnamespace Col\n\n')
    for name, ps in ((f'{LP}{M1}', pu), (f'{LP}N', pn)):
        for i, p in enumerate(ps):
            f.write(f'def {name}{i} : String :=\n  "{p}"\n\n')
        f.write(f'def {name}Parts : List String := [{", ".join(f"{name}{i}" for i in range(len(ps)))}]\n\n')
    f.write(f'/-- The {len(U)} {KIND1} keys. -/\ndef col{P}{M1} : LTree := treeOfKeys (keysOfText {RULE} {LP}{M1}Parts)\n\n')
    f.write(f'/-- The {len(N)} normal-play keys. -/\ndef col{P}N : LTree := treeOfKeys (keysOfText {RULE} {LP}NParts)\n\n')
    f.write('end Col\nend Cgt\n')


def sizes(total, k):
    q, r = divmod(total, k)
    return [q + (1 if i < r else 0) for i in range(k)]


su, sn = sizes(len(U), nu), sizes(len(N), nn)
CHK1 = 'chkS' if STAR else 'chkU'
PU = f'(fun k => (witOf {RULE} k).all ({CHK1} {RULE} col{P}{M1} col{P}N))'
PN = f'(fun k => (witOf {RULE} k).all (chkN {RULE} col{P}N))'
files = []
idx = 0
for mode, ss, tree, pred in ((M1, su, f'col{P}{M1}', PU), ('N', sn, f'col{P}N', PN)):
    start = 0
    for i, n in enumerate(ss):
        name = f'{P}Check{idx}'
        files.append(name)
        with open(f'Cgt/Col/{name}.lean', 'w') as f:
            f.write(f'import Cgt.Col.{P}Data\n' + ('import Cgt.Col.SoundStar\n' if STAR else '') + '\n')
            f.write(f'/-! {HEADER}: part {idx} of the finite check of {WHAT}, evaluated by\n'
                    '`native_decide`, which trusts the Lean compiler: it adds an axiom asserting the result of the\n'
                    'compiled evaluation. -/\n\n')
            f.write('namespace Cgt\nnamespace Col\n\n')
            f.write(f'theorem chk{P}{mode}_{i} : (({tree}.toList.drop {start}).take {n}).all {pred} = true := by\n'
                    '  native_decide\n\n')
            f.write('end Col\nend Cgt\n')
        start += n
        idx += 1


def assemble(mode, ss, tree, pred, stmt):
    arms = '\n'.join(f'      | {i}, _ => exact chk{P}{mode}_{i}' for i in range(len(ss)))
    return (f'theorem hc{mode}{SUF} : {stmt} := by\n'
            f'  have h : {tree}.toList.all {pred} = true :=\n'
            f'    all_of_sizes _ {ss} _ (by native_decide) fun i hi => by\n'
            f'      match i, hi with\n{arms}\n'
            f'      | _ + {len(ss)}, h => exact absurd h (by simp)\n'
            '  simp only [List.all_eq_true] at h\n  exact h\n\n')


with open(f'Cgt/Col/{P}Checks.lean', 'w') as f:
    f.write(('import Cgt.Col.SoundStar\n' if STAR else 'import Cgt.Col.Sound\n') + ''.join(f'import Cgt.Col.{n}\n' for n in files) + '\n')
    f.write(f'/-! {HEADER}: the chunks of the finite check of {WHAT}, assembled. -/\n\n')
    f.write('namespace Cgt\nnamespace Col\n\n')
    f.write(assemble(M1, su, f'col{P}{M1}', PU,
                     f'∀ k ∈ col{P}{M1}.toList, ∀ W ∈ witOf {RULE} k, {CHK1} {RULE} col{P}{M1} col{P}N W = true'))
    f.write(assemble('N', sn, f'col{P}N', PN,
                     f'∀ k ∈ col{P}N.toList, ∀ W ∈ witOf {RULE} k, chkN {RULE} col{P}N W = true'))
    f.write('end Col\nend Cgt\n')

print(f'{len(U)} {M1} + {len(N)} N witnesses; {len(pu)} + {len(pn)} string parts; {len(files)} check files')
print(f'{M1} chunks', su)
print('N chunks', sn)
