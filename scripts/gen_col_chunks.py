#!/usr/bin/env python3
"""Split the column check into kernel-sized chunks.

Reads the work per key (`ColGen.lean ... WORK`, one `MODE WORK` line per key, in tree order) and
writes Lean files `Cgt/Col/<NAME>Check<k>.lean`, each with at most PER theorems, every theorem
checking consecutive keys of total work at most BUDGET, and a block lemma `blk<NAME><MODE>_<k>`
covering the file's keys, in `Cgt/Col/<NAME>Blocks.lean`. Prints the blocks (file number, number
of keys) for the assembly.

Usage: gen_col_chunks.py WORK NAME BUDGET PER

The modes are `U` (Left stop) and `N`, or `S` (`≤ ∗`, checked by `chkS` of
`Cgt/Col/SoundStar.lean`) and `N`.
"""
import sys

work, name, budget, per = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
rows = [l.split() for l in open(work) if l.strip()]
MODES = 'SN' if any(m == 'S' for m, _ in rows) else 'UN'
out = {}
for mode in MODES:
    ws = [int(w) for m, w in rows if m == mode]
    sizes, cur, cnt = [], 0, 0
    for w in ws:
        if cnt and cur + w > budget:
            sizes.append(cnt); cur, cnt = 0, 0
        cur += w; cnt += 1
    if cnt: sizes.append(cnt)
    out[mode] = sizes
fileno, files, blocks = 0, [], {m: [] for m in MODES}
for mode in MODES:
    sizes = out[mode]
    tree = f'col{name}{mode}'
    fn = {'U': f'(chkU ruleP col{name}U col{name}N)', 'S': f'(chkS ruleP col{name}S col{name}N)',
          'N': f'(chkN ruleP col{name}N)'}[mode]
    starts, st = [], 0
    for c in sizes:
        starts.append(st); st += c
    for j in range(0, len(sizes), per):
        grp = list(range(j, min(len(sizes), j + per)))
        thms = [f'theorem chk{name}{mode}_{i} : (({tree}.toList.drop {starts[i]}).take {sizes[i]}).all '
                f'(fun k => (witOf ruleP k).all {fn}) = true := by decide +kernel' for i in grp]
        cs = [sizes[i] for i in grp]
        cases = '\n'.join(f'    | {k}, _ => exact chk{name}{mode}_{i}' for k, i in enumerate(grp))
        blk = (f'/-- Keys {starts[grp[0]]} to {starts[grp[0]] + sum(cs) - 1}. -/\n'
               f'theorem blk{name}{mode}_{fileno} : (({tree}.toList.drop {starts[grp[0]]}).take {sum(cs)}).all '
               f'(fun k => (witOf ruleP k).all {fn}) = true :=\n'
               f'  all_range_of_sizes _ {cs} _ {starts[grp[0]]} fun i hi => by\n'
               f'    match i, hi with\n{cases}\n'
               f'    | _ + {len(cs)}, h => exact absurd h (by simp)')
        blocks[mode].append((fileno, sum(cs), blk))
        fname = f'Cgt/Col/{name}Check{fileno}.lean'
        body = [f'import Cgt.Col.{name}Data'] + (['import Cgt.Col.SoundStar'] if MODES == 'SN' else []) + ['',
                f'/-! Machine-generated by `scripts/gen_col_chunks.py`: part {fileno} of the finite check, evaluated by the kernel. -/',
                '', 'namespace Cgt', 'namespace Col', ''] + thms + ['', 'end Col', 'end Cgt', '']
        open(fname, 'w').write('\n'.join(body))
        files.append(fname)
        fileno += 1
body = ['\n'.join(f'import Cgt.Col.{name}Check{k}' for k in range(len(files))), '',
        f'/-! Machine-generated by `scripts/gen_col_chunks.py`: one lemma per check file, covering its keys. -/',
        '', 'namespace Cgt', 'namespace Col', '']
for mode in MODES:
    body += [b[2] + '\n' for b in blocks[mode]]
body += ['end Col', 'end Cgt', '']
open(f'Cgt/Col/{name}Blocks.lean', 'w').write('\n'.join(body))
for mode in MODES:
    print(mode, [(b[0], b[1]) for b in blocks[mode]])
print('files', len(files))
