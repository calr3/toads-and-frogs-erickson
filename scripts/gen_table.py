#!/usr/bin/env python3
"""Generate the Lean files of a strategy table (`Cgt/Table.lean`) from the output of
tools/strategy.cpp (one position code per line, sorted: NAME_N.txt and, optionally, NAME_S.txt).

* Cgt/Tab/<Name>Data<k>.lean: the tables as text (`Table.parseDeltas`: the differences between
  consecutive codes, in base 32 with a continuation flag), split over files of about 6 MB;
* Cgt/Tab/<Name>Data.lean: `tab<Name>N`, `tab<Name>S`, parsed from the parts;
* Cgt/Tab/<Name>Check<i>.lean: one chunk of the check per file, evaluated by `native_decide`;
* Cgt/Tab/<Name>Checks.lean: the chunks assembled into `hN<Name>` and `hS<Name>`, the hypotheses of
  `Table.soundN` and `Table.soundS`.

Usage: python3 scripts/gen_table.py NAME PREFIX [CHUNKS_N CHUNKS_S]   (PREFIX_N.txt, PREFIX_S.txt)
"""
import os
import sys

name, prefix = sys.argv[1], sys.argv[2]
cn, cs = (int(sys.argv[3]), int(sys.argv[4])) if len(sys.argv) > 4 else (4, 4)
PART = 300000         # characters per string literal
FILE_PARTS = 20       # string literals per data file


def char(d):
    return chr(35 + d) if d < 57 else chr(36 + d)   # digit values 0..63, skipping the backslash


def enc(d):
    """A difference in base 32, most significant digit first; all but the last digit carry +32."""
    ds = []
    while True:
        ds.append(d % 32)
        d //= 32
        if d == 0:
            break
    ds.reverse()
    return ''.join(char(x + 32) for x in ds[:-1]) + char(ds[-1])


def text_of(xs):
    out, prev = [], 0
    for x in xs:
        out.append(enc(x - prev))
        prev = x
    return ''.join(out)


def load(path):
    if not os.path.exists(path):
        return []
    xs = [int(x) for x in open(path) if x.strip()]
    assert xs == sorted(xs) and len(set(xs)) == len(xs), path
    return xs


tabs = {'N': load(prefix + '_N.txt'), 'S': load(prefix + '_S.txt')}
HEADER = 'Machine-generated by `scripts/gen_table.py`'
os.makedirs('Cgt/Tab', exist_ok=True)
datafiles, partnames = [], {}
for k, xs in tabs.items():
    text = text_of(xs)
    parts = [text[i:i + PART] for i in range(0, len(text), PART)] or ['']
    partnames[k] = []
    for j in range(0, len(parts), FILE_PARTS):
        fn = f'{name}Data{k}{j // FILE_PARTS}'
        datafiles.append(fn)
        with open(f'Cgt/Tab/{fn}.lean', 'w') as f:
            f.write(f'/-! {HEADER}: text of the table `{k}` of `tab{name}{k}`, parts {j} to '
                    f'{min(j + FILE_PARTS, len(parts)) - 1}. -/\n\n')
            f.write('namespace Cgt\nnamespace Table\n\n')
            for i in range(j, min(j + FILE_PARTS, len(parts))):
                f.write(f'def tab{name}{k}{i} : String :=\n  "{parts[i]}"\n\n')
                partnames[k].append(f'tab{name}{k}{i}')
            f.write('end Table\nend Cgt\n')
with open(f'Cgt/Tab/{name}Data.lean', 'w') as f:
    f.write('import Cgt.Table\n' + ''.join(f'import Cgt.Tab.{fn}\n' for fn in datafiles) + '\n')
    f.write(f'/-! {HEADER}: a strategy table ({len(tabs["N"])} positions `≤ 0`, '
            f'{len(tabs["S"])} positions `≤ ∗`). -/\n\n')
    f.write('namespace Cgt\nnamespace Table\n\n')
    for k in tabs:
        f.write(f'def tab{name}{k} : Array Nat := ofParts [{", ".join(partnames[k])}]\n\n')
    f.write('end Table\nend Cgt\n')

pred = {'N': f'(fun x => chkN tab{name}N (decode x))', 'S': f'(fun x => chkS tab{name}S tab{name}N (decode x))'}
files, bounds = [], {}
for k, c in (('N', cn), ('S', cs)):
    size = len(tabs[k])
    if size == 0:
        continue
    c = min(c, size)
    bs = [size * i // c for i in range(c + 1)]
    bounds[k] = bs
    for i in range(c):
        fn = f'{name}Check{k}{i}'
        files.append(fn)
        with open(f'Cgt/Tab/{fn}.lean', 'w') as f:
            f.write(f'import Cgt.Tab.{name}Data\n\n')
            f.write(f'/-! {HEADER}: part {i} of the check of the table `{k}`, evaluated by `native_decide`,\n'
                    'which trusts the Lean compiler: it adds an axiom asserting the result of the compiled\n'
                    'evaluation. -/\n\n')
            f.write('namespace Cgt\nnamespace Table\n\n')
            f.write(f'theorem chk{name}{k}_{i} : rangeAll tab{name}{k} {pred[k]} {bs[i]} {bs[i + 1]} = true := by\n'
                    '  native_decide\n\n')
            f.write('end Table\nend Cgt\n')

with open(f'Cgt/Tab/{name}Checks.lean', 'w') as f:
    f.write(''.join(f'import Cgt.Tab.{fn}\n' for fn in files) + '\n')
    f.write(f'/-! {HEADER}: the chunks of the check assembled. -/\n\n')
    f.write('namespace Cgt\nnamespace Table\n\n')
    for k, bs in bounds.items():
        c = len(bs) - 1
        f.write(f'theorem size{name}{k} : tab{name}{k}.size = {bs[-1]} := by native_decide\n\n')
        # fold the chunks from the right: rangeAll 0 size
        expr = f'chk{name}{k}_{c - 1}'
        for i in range(c - 2, -1, -1):
            expr = f'rangeAll_append (by decide) (by decide) chk{name}{k}_{i} ({expr})'
        stmt = 'chkN tab{0}N (decode x) = true'.format(name) if k == 'N' else \
            'chkS tab{0}S tab{0}N (decode x) = true'.format(name)
        f.write(f'theorem h{k}{name} : ∀ x ∈ tab{name}{k}, {stmt} := by\n'
                f'  have h : rangeAll tab{name}{k} {pred[k]} 0 {bs[-1]} = true :=\n    {expr}\n'
                f'  rw [← size{name}{k}] at h\n'
                '  exact forall_of_rangeAll h\n\n')
    f.write('end Table\nend Cgt\n')

print(f'{name}: N {len(tabs["N"])}, S {len(tabs["S"])}; check files: {len(files)}')
