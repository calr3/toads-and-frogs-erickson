# Write the Lean files of the row a = 3 from the plans of gen_lean6.py: the invariant (Cgt/RowA3/Inv.lean) and
# the closure lemmas (Cgt/RowA3/Close*.lean).   Usage: python3 emit_lean6.py OUTDIR PLAN.pkl [PLAN.pkl ...]
import sys, pickle, os
from z3check6 import toad, name
from gen_lean6 import ORDERS, lmoves, neg
OUT = sys.argv[1]; cases = None; plan = {}
for fn in sys.argv[2:]:
    cs, pl = pickle.load(open(fn, 'rb')); cases = cs; plan.update(pl)
os.makedirs(OUT, exist_ok=True)
NAMES = ['g%d' % k for k in range(7)]; GS = ' '.join(NAMES)
CHUNK = 120
def bl(c): return ', '.join('true' if (c >> i) & 1 else 'false' for i in range(6))
def form_lean(a, names=NAMES):
    parts = []
    for k in range(7):
        if a[k] == 0: continue
        t = f"({names[k]}:Int)" if abs(a[k]) == 1 else f"{abs(a[k])} * ({names[k]}:Int)"
        parts.append((('-' if a[k] < 0 else '') + t) if not parts else ((' - ' if a[k] < 0 else ' + ') + t))
    return ''.join(parts) if parts else '0'
def lit_lean(l):
    a, op, m, v = l; F = form_lean(a)
    return {'ge': f"{F} ≥ {v}", 'le': f"{F} ≤ {v}", 'eq': f"{F} = {v}", 'mod': f"({F}) % {m} = {v}", 'nmod': f"({F}) % {m} ≠ {v}"}[op]
def conj(lits): return ' ∧ '.join('(' + lit_lean(l) + ')' for l in lits) if lits else 'True'
def bal(lo, hi, f):   # balanced disjunction of f(lo) .. f(hi - 1)
    if hi - lo == 1: return f(lo)
    mid = (lo + hi) // 2; return '(' + bal(lo, mid, f) + ') ∨ (' + bal(mid, hi, f) + ')'
def inj(k, lo, hi, x):
    if hi - lo == 1: return x
    mid = (lo + hi) // 2
    return 'Or.inl (' + inj(k, lo, mid, x) + ')' if k < mid else 'Or.inr (' + inj(k, mid, hi, x) + ')'
def pat(lo, hi):
    if hi - lo == 1: return 'h'
    mid = (lo + hi) // 2; return '(' + pat(lo, mid) + ' | ' + pat(mid, hi) + ')'
HDR = "/-! Machine-generated by `tools/presburger/a3/emit_lean6.py`; do not edit. -/\n"
OPT = "set_option linter.unusedVariables false\nset_option maxHeartbeats 4000000\nset_option maxRecDepth 100000\n"
# ---- the invariant
L = ["import Cgt.RowA3.Moves", "", HDR, "namespace Cgt", "", OPT]
for c in ORDERS:
    n = len(cases[c]); O = name(c)
    for k, (a, lits) in enumerate(cases[c]): L.append(f"def case_{O}_{k} ({GS} : Nat) : Prop :=\n  {conj(lits)}")
    L.append(f"\n/-- `{O}`: {n} cases. -/")
    L.append(f"def good_{O} ({GS} : Nat) : Prop :=\n  " + (bal(0, n, lambda k: f"case_{O}_{k} {GS}") if n else "False") + "\n")
    for k in range(n): L.append(f"theorem good_{O}_{k} {{{GS} : Nat}} (h : case_{O}_{k} {GS}) : good_{O} {GS} := by\n  unfold good_{O}; exact {inj(k, 0, n, 'h')}")
    L.append("")
L.append("/-- The invariant: Right, moving second, wins every position satisfying it. -/\ndef inv3 : P6 → Prop")
for c in ORDERS: L.append(f"  | ⟨{bl(c)}, {', '.join(NAMES)}⟩ => good_{name(c)} {GS}")
L.append("  | _ => False\n\nend Cgt")
open(f"{OUT}/Inv.lean", "w").write("\n".join(L) + "\n")
# ---- closure lemmas
def gap_exprs(d): return [NAMES[k] if d[k] == 0 else (f"{NAMES[k]} + 1" if d[k] == 1 else f"{NAMES[k]} - 1") for k in range(7)]
def mem_term(j, kind):
    x = f"rm{j + 1}_{kind}6 (by omega)" + (" (by omega)" if kind == 'jump' else "")
    s = x if j == 5 else f"Or.inl ({x})"
    for _ in range(j): s = f"Or.inr ({s})"
    return "mem_rms6.2 (" + s + ")"
nleaf = [0]
def emit_tree(t, cnt):
    if t[0] == 'fail': return ["sorry"]
    if t[0] == 'dead': nleaf[0] += 1; return ["exfalso; omega"]
    if t[0] == 'leaf':
        _, j, kind, c3, ti = t; O3 = name(c3); nleaf[0] += 1
        return [f"exact ⟨_, {mem_term(j, kind)}, by show good_{O3} _ _ _ _ _ _ _; exact good_{O3}_{ti} (by unfold case_{O3}_{ti}; omega)⟩"]
    _, l, y, n = t; cnt[0] += 1; s = f"s{cnt[0]}"
    out = [f"by_cases {s} : {lit_lean(l)}"]
    for sub in (emit_tree(y, cnt), emit_tree(n, cnt)):
        out.append("· " + sub[0]); out.extend("  " + x for x in sub[1:])
    return out
files = []
for c in ORDERS:
    O = name(c); n = len(cases[c]); chunks = []
    asm = []
    for (i, kind, c2, dL, condL, da) in lmoves(c):
        q = f"(⟨{bl(c2)}, {', '.join(gap_exprs(dL))}⟩ : P6)"
        hyps = f"(hc : g{i + 1} ≠ 0)" if kind == 'slide' else f"(hc : g{i + 1} = 0) (hc' : g{i + 2} ≠ 0)"
        nm = f"cl_{O}_{i}_{kind}"; args = f"{GS} h hc" + (" hc'" if kind == 'jump' else "")
        for p0 in range(0, n, CHUNK):
            fn = f"Close_{O}_{i}_{kind}_{p0 // CHUNK}"; chunks.append(fn)
            B = ["import Cgt.RowA3.Inv", "", HDR, "namespace Cgt", "", OPT]
            for s in range(p0, min(n, p0 + CHUNK)):
                t = plan.get((c, i, kind, s), ('fail', 'missing'))
                B.append(f"theorem {nm}_{s} ({GS} : Nat) (h : case_{O}_{s} {GS}) {hyps} :\n    ∃ r, r ∈ {q}.rms ∧ inv3 r := by\n  unfold case_{O}_{s} at h")
                B.extend("  " + x for x in emit_tree(t, [0])); B.append("")
            B.append("end Cgt"); open(f"{OUT}/{fn}.lean", "w").write("\n".join(B) + "\n")
        asm.append(f"theorem {nm} ({GS} : Nat) (h : good_{O} {GS}) {hyps} :\n    ∃ r, r ∈ {q}.rms ∧ inv3 r := by\n  unfold good_{O} at h")
        if n == 0: asm.append("  exact h.elim")
        elif n == 1: asm.append(f"  exact {nm}_0 {args}")
        else:
            asm.append(f"  rcases h with {pat(0, n)}")
            for s in range(n): asm.append(f"  · exact {nm}_{s} {args}")
        asm.append("")
    A = [f"import Cgt.RowA3.{x}" for x in chunks] + (["import Cgt.RowA3.Inv"] if not chunks else []) + ["", HDR, "namespace Cgt", "", OPT] + asm
    A.append(f"theorem close_{O} ({GS} : Nat) (h : good_{O} {GS}) (q : P6)\n    (hq : q ∈ (⟨{bl(c)}, {', '.join(NAMES)}⟩ : P6).lms) : ∃ r, r ∈ q.rms ∧ inv3 r := by\n  rcases mem_lms6.1 hq with e | e | e | e | e | e")
    for i in range(6):
        if not toad(c, i): A.append(f"  · simp [P6.lm{i + 1}] at e"); continue
        has_jump = i + 1 < 6 and not toad(c, i + 1)
        A.append(f"  · by_cases z : g{i + 1} = 0")
        if has_jump:
            A.append(f"    · by_cases z' : g{i + 2} = 0\n      · simp [P6.lm{i + 1}, z, z'] at e\n      · rw [lm{i + 1}_jump6 z z'] at e; cases e; exact cl_{O}_{i}_jump {GS} h z z'")
        else: A.append(f"    · simp [P6.lm{i + 1}, z] at e")
        A.append(f"    · rw [lm{i + 1}_slide6 z] at e; cases e; exact cl_{O}_{i}_slide {GS} h z")
    A.append("\nend Cgt"); open(f"{OUT}/Close_{O}.lean", "w").write("\n".join(A) + "\n"); files.append(f"Close_{O}")
print("cases", sum(len(v) for v in cases.values()), "leaves", nleaf[0], "files", len(os.listdir(OUT)))
