# Emit Cgt/RowA2Odd/Inv.lean (the invariant) and Cgt/RowA2Odd/Close*.lean (closure lemmas) from plan.pkl.
import pickle, os
from gen_lean import ORDERS, ONAME, lit_lean, lmoves, toad, neg
cells, plan = pickle.load(open('plan.pkl', 'rb'))
import json, sys
STRAT = json.load(open('strategies.json')) if os.path.exists('strategies.json') else {}
LEAVES = []   # leaf id -> (region literals, leaf)
NAMES = ['g0', 'g1', 'g2', 'g3', 'g4']
OUT = '../../Cgt/RowA2Odd'
os.makedirs(OUT, exist_ok=True)
def bl(c): return ', '.join('true' if (c >> i) & 1 else 'false' for i in range(4))
def cell_lean(cell): return ' ∧ '.join('(' + lit_lean(l, NAMES) + ')' for l in cell)
def disj(i, n, x):
    if n == 1: return x
    s = x if i == n - 1 else f"Or.inl ({x})"
    for _ in range(i): s = f"Or.inr ({s})"
    return s
HDR = "/-! Machine-generated by `tools/presburger/emit_lean.py`; do not edit. -/\n"
# --- invariant
inv = ["import Cgt.Shape4", "", HDR, "namespace Cgt", "", "set_option linter.unusedVariables false", ""]
for c in ORDERS:
    cs = cells[c]
    inv.append(f"/-- `{ONAME[c]}`: {len(cs)} cases. -/")
    inv.append(f"def good{ONAME[c]} (g0 g1 g2 g3 g4 : Nat) : Prop :=")
    inv.append("  " + "\n  ∨ ".join('(' + cell_lean(x) + ')' for x in cs))
    inv.append("")
inv.append("/-- The invariant: Right, moving second, wins every position satisfying it. -/")
inv.append("def inv2 : P4 → Prop")
for c in ORDERS:
    inv.append(f"  | ⟨{bl(c)}, g0, g1, g2, g3, g4⟩ => good{ONAME[c]} g0 g1 g2 g3 g4")
inv.append("  | _ => False")
inv.append("")
inv.append("end Cgt")
open(f"{OUT}/Inv.lean", "w").write("\n".join(inv) + "\n")
# --- closure lemmas, one file per order
def gap_exprs(d):
    out = []
    for k in range(5):
        out.append(NAMES[k] if d[k] == 0 else (f"{NAMES[k]} + 1" if d[k] == 1 else f"{NAMES[k]} - 1"))
    return out
def mem_term(j, kind):
    x = f"rm{j + 1}_{kind} (by omega)" + (" (by omega)" if kind == 'jump' else "")
    return "mem_rms.2 (" + disj(j, 4, x) + ")"
def res_prefix(vs):
    out = []
    for v in vs:
        alts = " ∨ ".join(f"{v} % 6 = {r}" for r in range(6))
        out.append(f"rcases (show {alts} by omega) with hr | hr | hr | hr | hr | hr")
    return " <;> ".join(out) + " <;> "
def res1_prefix(v, m):
    alts = " ∨ ".join(f"{v} % {m} = {r}" for r in range(m)); pat = " | ".join(["hr"] * m)
    return f"rcases (show {alts} by omega) with {pat} <;> "
def leaf_line(t, region, strat):
    _, j, kind, c3, dT, ti = t
    n3 = len(cells[c3]); fin = "omega" if n3 == 1 else "exact " + disj(ti, n3, "by omega")
    body = f"exact ⟨_, {mem_term(j, kind)}, by simp only [inv2, good{ONAME[c3]}]; {fin}⟩"
    if strat and strat[0] == 'vals':
        var, vals = strat[1], strat[2]
        alts = " ∨ ".join(f"{var} = {v}" for v in vals)
        pat = " | ".join(["hv"] * len(vals))
        if len(vals) == 1: return f"obtain hv : {var} = {vals[0]} := by omega" + "\n" + "subst hv" + "\n" + body
        return f"rcases (show {alts} by omega) with {pat} <;> subst hv <;> {body}"
    if strat and strat[0] == 'res': return res_prefix(strat[1]) + body
    if strat and strat[0] == 'res1': return res1_prefix(strat[1], strat[2]) + body
    return body
def emit_tree(t, cnt, region):
    """Lines of a tactic proof, without base indentation."""
    if t[0] == 'dead':
        lid = len(LEAVES); LEAVES.append((region, t)); st = STRAT.get(str(lid))
        if st and st[0] == 'vals':
            var, vals = st[1], st[2]; alts = " ∨ ".join(f"{var} = {v}" for v in vals); pat = " | ".join(["hv"] * len(vals))
            return [f"exfalso; rcases (show {alts} by omega) with {pat} <;> subst hv <;> omega  -- leaf {lid}"]
        if st and st[0] == 'res': return ["exfalso; " + res_prefix(st[1]) + f"omega  -- leaf {lid}"]
        if st and st[0] == 'res1': return ["exfalso; " + res1_prefix(st[1], st[2]) + f"omega  -- leaf {lid}"]
        return [f"exfalso; omega  -- leaf {lid}"]
    if t[0] == 'leaf':
        lid = len(LEAVES); LEAVES.append((region, t))
        txt = leaf_line(t, region, STRAT.get(str(lid)))
        lines = txt.split("\n")
        lines[0] = lines[0] + f"  -- leaf {lid}"
        return lines
    _, l, y, n = t; cnt[0] += 1; s = f"s{cnt[0]}"
    out = [f"by_cases {s} : {lit_lean(l, NAMES)}"]
    for sub in (emit_tree(y, cnt, region + [l]), emit_tree(n, cnt, region + [neg(l)])):
        out.append("· " + sub[0]); out.extend("  " + x for x in sub[1:])
    return out
for c in ORDERS:
    L = [f"import Cgt.RowA2Odd.Moves", "", HDR, "namespace Cgt", "", "set_option linter.unusedVariables false", ""]
    for (i, kind, c2, dL, condL) in lmoves(c):
        trees = plan[(c, i, kind)]
        q = f"(⟨{bl(c2)}, {', '.join(gap_exprs(dL))}⟩ : P4)"
        hyps = f"(hc : g{i + 1} ≠ 0)" if kind == 'slide' else f"(hc : g{i + 1} = 0) (hc' : g{i + 2} ≠ 0)"
        name = f"cl_{ONAME[c]}_{i}_{kind}"
        n = len(trees); cnt = [0]
        for s_, t in enumerate(trees):
            L.append("set_option maxHeartbeats 2000000 in")
            L.append(f"theorem {name}_{s_} (g0 g1 g2 g3 g4 : Nat) (h : {cell_lean(cells[c][s_])}) {hyps} :")
            L.append(f"    ∃ r, r ∈ {q}.rms ∧ inv2 r := by")
            L.extend("  " + x for x in emit_tree(t, cnt, list(cells[c][s_]) + list(condL)))
            L.append("")
        L.append(f"theorem {name} (g0 g1 g2 g3 g4 : Nat) (h : good{ONAME[c]} g0 g1 g2 g3 g4) {hyps} :")
        L.append(f"    ∃ r, r ∈ {q}.rms ∧ inv2 r := by")
        L.append(f"  unfold good{ONAME[c]} at h")
        args = "g0 g1 g2 g3 g4 h hc" + (" hc'" if kind == 'jump' else "")
        if n > 1:
            L.append("  rcases h with " + " | ".join(["h"] * n))
            for s_ in range(n): L.append(f"  · exact {name}_{s_} {args}")
        else: L.append(f"  exact {name}_0 {args}")
        L.append("")
    # assembly: every Left move
    L.append(f"theorem close_{ONAME[c]} (g0 g1 g2 g3 g4 : Nat) (h : good{ONAME[c]} g0 g1 g2 g3 g4) (q : P4)")
    L.append(f"    (hq : q ∈ (⟨{bl(c)}, g0, g1, g2, g3, g4⟩ : P4).lms) : ∃ r, r ∈ q.rms ∧ inv2 r := by")
    L.append("  rcases mem_lms.1 hq with e | e | e | e")
    for i in range(4):
        L.append("  · " + f"-- piece {i + 1}")
        if not toad(c, i):
            L.append(f"    simp [P4.lm{i + 1}] at e"); continue
        has_jump = i + 1 < 4 and not toad(c, i + 1)
        L.append(f"    by_cases z : g{i + 1} = 0")
        if has_jump:
            L.append(f"    · by_cases z' : g{i + 2} = 0")
            L.append(f"      · simp [P4.lm{i + 1}, z, z'] at e")
            L.append(f"      · rw [lm{i + 1}_jump z z'] at e; cases e; exact cl_{ONAME[c]}_{i}_jump g0 g1 g2 g3 g4 h z z'")
        else:
            L.append(f"    · simp [P4.lm{i + 1}, z] at e")
        L.append(f"    · rw [lm{i + 1}_slide z] at e; cases e; exact cl_{ONAME[c]}_{i}_slide g0 g1 g2 g3 g4 h z")
    L.append("")
    L.append("end Cgt")
    open(f"{OUT}/Close{ONAME[c]}.lean", "w").write("\n".join(L) + "\n")
pickle.dump(LEAVES, open('leaves.pkl', 'wb'))
